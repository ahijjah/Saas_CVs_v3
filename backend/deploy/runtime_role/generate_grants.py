"""Writes grants.sql from usage_inventory.py: exactly the statements the source needs, per table. Regenerate after schema changes; review the diff.

Deliberately NOT granted to the runtime role: ownership, CREATE, TRUNCATE, REFERENCES, TRIGGER, membership in any role, and any BYPASSRLS or
SUPERUSER attribute. The history table is granted SELECT and INSERT only, and UPDATE, DELETE and TRUNCATE are revoked explicitly.
"""
from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import usage_inventory as u  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent
BACKEND = HERE.parents[1]
ROLE = "cv_runtime"
VERBS = {"SELECT": "SELECT", "INSERT": "INSERT", "UPDATE": "UPDATE", "DELETE": "DELETE"}
HISTORY = "requirements_analysis_log"


def render() -> str:
    tables = u.schema_tables(BACKEND / "db" / "schema.sql", BACKEND / "db" / "migrations") - {"if"}
    usage, dynamic = u.scan(tables)
    lines = [
        "-- GENERATED by deploy/runtime_role/generate_grants.py from the source (usage_inventory.py). Do not edit by hand; regenerate and review.",
        "-- Runtime role: a login role that is NOT a superuser, NOT BYPASSRLS, NOT the owner of any object, and a member of no role (NOINHERIT).",
        "-- Apply to a disposable database first (tests/test_runtime_role_plan.py). Nothing here changes an existing role, policy or owner.",
        "--",
        "-- Role creation (idempotent). The password is NOT in this file: the operator sets it with ALTER ROLE ... PASSWORD outside the repository.",
        "DO $$ BEGIN",
        f"    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{ROLE}') THEN",
        f"        CREATE ROLE {ROLE} LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION NOINHERIT;",
        "    END IF;",
        "END $$;",
        f"ALTER ROLE {ROLE} NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION NOINHERIT;",
        "",
        "SET search_path = cv_analyzer;",
        f"GRANT USAGE ON SCHEMA cv_analyzer TO {ROLE};",
        f"REVOKE CREATE ON SCHEMA cv_analyzer FROM {ROLE};",
        "",
        "-- Table privileges, from the statements found in the source (SELECT: FROM/JOIN; INSERT: INTO; UPDATE: UPDATE ... SET; DELETE: DELETE FROM).",
    ]
    for name in sorted(usage):
        verbs = sorted(VERBS[v] for v in usage[name])
        if name == HISTORY:
            verbs = [v for v in verbs if v in ("SELECT", "INSERT")]        # append-only: never UPDATE or DELETE
        lines.append(f"GRANT {', '.join(verbs)} ON {name} TO {ROLE};")
    lines += [
        "",
        "-- Sequences behind serial and bigserial keys (inserts need USAGE). A new sequence needs its own grant after the migration that creates it.",
        f"GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA cv_analyzer TO {ROLE};",
        "",
        "-- The history table: no modification, deletion or truncation by the runtime role, whatever the table-level grants above say.",
        f"REVOKE UPDATE, DELETE, TRUNCATE ON {HISTORY} FROM {ROLE};",
        "",
        "-- Not granted (on purpose): TRUNCATE, REFERENCES, TRIGGER, ownership, CREATE, any membership. Verified by the test.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    (HERE / "grants.sql").write_text(render(), encoding="utf-8")
    print("wrote", HERE / "grants.sql")
